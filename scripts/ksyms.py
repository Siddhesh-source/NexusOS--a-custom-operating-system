"""Make the kernel's symbol table: a C file listing every function's start
address, size and name, read from the linked kernel ELF.

The kernel links this table in so a panic can print `function+offset`
instead of bare addresses. The build links twice: once with an empty table
to learn the addresses, then again with the real table. The table lives in
read-only data placed after all code, so adding it never moves a function
(build.py checks that).

Only the Python standard library is used: the ELF file is parsed by hand.
"""
from __future__ import annotations
import struct
from pathlib import Path

SHT_SYMTAB = 2
STT_NOTYPE, STT_FUNC = 0, 2


def read_functions(elf_path: Path) -> list[tuple[int, int, str]]:
    """Return sorted (address, size, name) for every code symbol."""
    data = elf_path.read_bytes()
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        raise ValueError(f"{elf_path} is not a little-endian ELF64 file")

    shoff, = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x3A)
    sections = []
    for i in range(shnum):
        (name, stype, _flags, addr, off, size, link, _info, _align,
         entsize) = struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize)
        sections.append((name, stype, addr, off, size, link, entsize))

    def cstr(table_off: int, idx: int) -> str:
        end = data.index(b"\0", table_off + idx)
        return data[table_off + idx:end].decode("utf-8", "replace")

    shstr_off = sections[shstrndx][3]
    text_idx = {i for i, s in enumerate(sections)
                if cstr(shstr_off, s[0]) == ".text"}

    funcs: dict[int, tuple[int, str]] = {}
    for _name, stype, _addr, off, size, link, entsize in sections:
        if stype != SHT_SYMTAB:
            continue
        str_off = sections[link][3]
        for j in range(size // entsize):
            st_name, st_info, _other, st_shndx, st_value, st_size = \
                struct.unpack_from("<IBBHQQ", data, off + j * entsize)
            kind = st_info & 0xF
            if st_shndx not in text_idx or kind not in (STT_FUNC, STT_NOTYPE):
                continue
            name = cstr(str_off, st_name)
            # Skip assembler-local labels (".loop", "foo.bar") and linker
            # markers such as __text_start; they are not functions.
            if not name or "." in name or name.startswith("__"):
                continue
            # Prefer a FUNC entry (it has a size) over a bare label.
            if st_value not in funcs or kind == STT_FUNC:
                funcs[st_value] = (st_size, name)
    return sorted((a, s, n) for a, (s, n) in funcs.items())


def write_table(funcs: list[tuple[int, int, str]], out: Path) -> None:
    lines = [
        "/* Generated by scripts/ksyms.py from the kernel ELF. Do not edit. */",
        '#include "backtrace.h"',
        "",
        "const struct ksym ksym_table[] = {",
    ]
    for addr, size, name in funcs:
        lines.append(f'    {{ 0x{addr:016x}ULL, 0x{size:x}ULL, "{name}" }},')
    lines.append("    { 0, 0, 0 },   /* end marker; also keeps the array non-empty */")
    lines.append("};")
    lines.append(f"const uint64_t ksym_count = {len(funcs)};")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
